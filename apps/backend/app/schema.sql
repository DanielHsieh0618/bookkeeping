CREATE TABLE IF NOT EXISTS users (
    user_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_id VARCHAR(255) NOT NULL UNIQUE,
    email     VARCHAR(254) NOT NULL,
    user_name VARCHAR(255) NOT NULL,
    uuid      VARCHAR(36)  NOT NULL
);

CREATE TABLE IF NOT EXISTS categories (
    category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INTEGER NOT NULL REFERENCES users (user_id),
    category_name VARCHAR(255) NOT NULL,
    category_icon VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS records (
    record_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_date VARCHAR(64) NOT NULL,
    record_type VARCHAR(32) NOT NULL,
    amount      NUMERIC(12, 2) NOT NULL,
    category_id INTEGER REFERENCES categories (category_id),
    user_id     INTEGER NOT NULL REFERENCES users (user_id),
    description TEXT NOT NULL
);

-- Income records have no category. Idempotent, so databases created before this change catch up on startup.
ALTER TABLE records ALTER COLUMN category_id DROP NOT NULL;
